/** Pick the root CA that signs the given MQTT broker hostname. */
export function rootCAForMqttHost(hostname: string): string {
  if (/^[^.]+-ats\.iot\.[^.]+\.amazonaws\.com$/.test(hostname)) {
    return AMAZON_ROOT_CA_1;
  }
  if (/^[^.]+\.iot\.ruic\.lgthinq\.com$/.test(hostname)) {
    return COMODO_AAA_CERTIFICATE_SERVICES;
  }
  return VERISIGN_CLASS3_G5;
}
